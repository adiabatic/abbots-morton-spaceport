def tuple_memo(n: int) -> int:
    memo: dict[tuple, int] = {}
    acc = 0
    for i in range(n):
        key = (RUNES[i % 8], STANCES[i % 4], HEIGHTS[i % 4], HEIGHTS[(i + 1) % 4], i % 3)
        hit = memo.get(key)
        if hit is None:
            memo[key] = i
