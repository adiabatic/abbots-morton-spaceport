"""The memo sub-question, in isolation: 2.43 M lookups on the kernel's 10-tuple memo key.

Python pays a tuple of `str|None` plus four frozen-dataclass RightTokens, exactly as
settle.Engine.transition_trace does; the Rust and Go ports pay a 10-byte packed struct. The key stream is
generated by the same splitmix64 in all three, and every lookup result is folded into a printed checksum.
"""

import json
import sys
import time
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from rebuild.tools.peak_rss import peak_rss_self_bytes  # noqa: E402

MASK = (1 << 64) - 1
N_KEYS = 900_000
N_LOOKUPS = 2_428_420  # the real kernel's measured transition_trace call count


def mix(x: int) -> int:
    z = (x + 0x9E3779B97F4A7C15) & MASK
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK
    return z ^ (z >> 31)


@dataclass(frozen=True)
class RightToken:
    kind: str
    rune: str | None = None


KINDS = ("letter", "edge", "space", "zwnj", "namer-dot")
RUNES = tuple(f"qs{i:02d}" for i in range(18))
STANCES = tuple(f"st{i}" for i in range(4))
SEAMS = (None, "baseline", "x-height", "y6", "top")
TOKENS = tuple(RightToken("letter", RUNES[i]) for i in range(18)) + (
    RightToken("edge"),
    RightToken("space"),
    RightToken("zwnj"),
    RightToken("namer-dot"),
    RightToken("unknown"),
)


def key_for(i: int) -> tuple:
    s = mix(i)
    return (
        KINDS[s % 5],
        RUNES[(s >> 3) % 18],
        STANCES[(s >> 8) % 4],
        SEAMS[(s >> 12) % 5],
        (s >> 16) % 3,
        RUNES[(s >> 20) % 18],
        TOKENS[(s >> 24) % 23],
        TOKENS[(s >> 29) % 23],
        TOKENS[(s >> 34) % 23],
        TOKENS[(s >> 39) % 23],
    )


def main() -> None:
    rss0 = peak_rss_self_bytes()
    t0 = time.perf_counter()
    memo: dict[tuple, int] = {}
    for i in range(N_KEYS):
        memo[key_for(i)] = i
    build = time.perf_counter() - t0
    rss1 = peak_rss_self_bytes()

    t1 = time.perf_counter()
    checksum = 0
    hits = 0
    for j in range(N_LOOKUPS):
        idx = mix(j ^ 0xABCDEF) % (N_KEYS * 2)
        v = memo.get(key_for(idx))
        if v is not None:
            checksum = (checksum + v) & MASK
            hits += 1
    lookup = time.perf_counter() - t1

    print(
        json.dumps(
            {
                "impl": "python",
                "n_keys": len(memo),
                "n_lookups": N_LOOKUPS,
                "build_seconds": build,
                "lookup_seconds": lookup,
                "ns_per_lookup": lookup * 1e9 / N_LOOKUPS,
                "hits": hits,
                "checksum": checksum,
                "rss_delta_bytes": rss1 - rss0,
                "bytes_per_entry": (rss1 - rss0) / max(1, len(memo)),
            }
        )
    )


if __name__ == "__main__":
    sys.exit(main())
