"""Shared frozen dataclasses for the M1 pipeline (rebuild/M1-PLAN.md section 5): `ResolvedSpec` and the runes, stances, surfaces, and policy records under it, `CellId` and `Settled`, `CellPlan` (from `surface.resolve_cell`), and `GlyphRecord` (from `geometry.realize`).

`kernel_io` serializes a `ResolvedSpec` from these field definitions, and the Rust crate lists the same fields by hand (`rebuild/kernel-rs/src/model.rs` and `parse.rs`). A change here must also be made in the crate; the spec-echo test in `rebuild/test_kernel_io.py` fails until it is.

The adjustment tokens in `CellId.adjustments` are generated by settlement and read by geometry, never authored, and their order matters:

- `locked`: the ZWNJ chokepoint twin, with the entry side removed.
- `en-ext-N` / `ex-ext-N`: lengthen the connector on the named side by N pixels in the same row.
- `en-con-N` / `ex-con-N`: shorten it by N pixels.
- `en-trim-N` / `ex-trim-N`: receiver-side removal of N pixels of same-row ink that leaves the anchor in place, which exempts that side from the anchor convention.
- `en-bind-<bitmap>` / `ex-bind-<bitmap>`: a `bind:` extend or contract that substitutes a named hand-drawn sibling bitmap. An extend writes its bind token before its `ext` token, because geometry applies tokens in order and lengthens the drawing the binding put in place.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Collection, Literal, Mapping

Height = str  # "baseline" | "x-height" | "y6" | "top" (registry-validated)

NONE_STATE = "none"
WITHDRAWN_SUFFIX = "-withdrawn"

RIGHT_WINDOW_SLOTS = 4  # right1..rightN, the raw window settlement sees. table.py checks its Transition and Rule slot counts against this at import, so raising the chain cap without widening the table fails at import instead of emitting records that read past the window.
RIGHT_CHAIN_CAP = (
    RIGHT_WINDOW_SLOTS - 1
)  # the most then: hops past the immediate right neighbor that spec_load's lint allows, counting hops inside except: entries; derived from the window size


@dataclass(frozen=True, slots=True)
class CellId:
    rune: str  # family name (ligatures are ordinary runes)
    stance: str
    entry: Height | None
    exit: Height | None
    adjustments: tuple[str, ...] = ()  # ordered, generated: ("en-ext-1",), ("locked",), () — never authored


@dataclass(frozen=True, slots=True)
class Settled:
    cell: CellId
    seam: Height | None  # the committed seam toward the next position
    extension: int  # summed connector pixels carried on this seam by this side


@dataclass(frozen=True)
class Provenance:
    file: str
    path: str

    def __str__(self) -> str:
        return f"{self.file}:{self.path}"


@dataclass(frozen=True)
class Condition:
    """One side of a `when:` — the closed static vocabulary of design section 3.4. Axis values are tuples even when authored as scalars; empty tuple means the axis is unconstrained."""

    family: tuple[str, ...] = ()
    klass: tuple[str, ...] = ()  # predicate classes or rune-local groups ("class:" in YAML)
    stance: tuple[str, ...] = ()
    joined_at: Height | None = None  # the height of the join being decided; "none" = the seam did not join
    stroke: str | None = None
    is_token: str | None = None  # "boundary" | "space" | "zwnj" | "namer-dot" ("is:" in YAML)
    except_: tuple["Condition", ...] = ()
    then: "Condition | None" = None  # right-only static hop, lint-capped chain; forbidden on refuse records


@dataclass(frozen=True)
class When:
    left: Condition | None = None
    right: Condition | None = None
    self_entry: str | None = None  # "live" | "none"
    self_exit: str | None = None
    word: str | None = None  # "initial" | "medial" | "final" | "isolated"
    feature: str | None = None


@dataclass(frozen=True)
class Stub:
    """Same-row attachment ink at a side's anchor row (design section 3.2). `inks_when` names the state in which the columns are inked. `joined` is a connector nub that is blank in the base drawing and inked when the side joins. `withdrawn` is ink in the base drawing that is removed when the side joins, as in qsGay."""

    cols: tuple[int, ...]
    inks_when: str  # "joined" | "withdrawn"


@dataclass(frozen=True)
class SurfaceRow:
    """One entry or exit row: a height, an anchor x, and the optional bindings, scopes, and exceptions."""

    height: Height
    x: int
    stroke: str | None = None
    joined: str | None = None  # named sibling bitmap used when this side is live
    joined_x: int | None = None  # per-row anchor override that travels with the joined binding
    withdrawal: str | None = None  # named sibling bitmap, or "safe" (compiler-verified no reaching ink)
    stub: Stub | None = None
    scope: tuple[Condition, ...] = ()  # `from:` on entries, `toward:` on exits; empty = unscoped
    selectable: bool = (
        True  # False: settlement never selects this entry, and its anchor is kept for GPOS only (CellPlan.entry_curs_only)
    )
    ink_y: int | None = (
        None  # the old font's exit_ink_y: the row where the anchor and seam-gap checks read the exit's ink when the exit anchor sits off the stroke's row
    )
    x_off_convention: bool = False
    provenance: Provenance | None = None


@dataclass(frozen=True)
class Pairing:
    entry: str  # a height or "none"
    exit: str


@dataclass(frozen=True)
class Pairings:
    never: tuple[Pairing, ...] = ()
    only: tuple[Pairing, ...] | None = None


@dataclass(frozen=True)
class CellBinding:
    """An explicit `cells:` row: the named composition when side bindings touch one cell. `entry`/`exit` are state tokens: a height, a height plus "-withdrawn", or "none"."""

    entry: str
    exit: str
    bitmap: str
    entry_x: int | None = None
    exit_x: int | None = None
    provenance: Provenance | None = None


@dataclass(frozen=True)
class Unlock:
    feature: str
    entry: Height | None = None
    exit: Height | None = None
    pairing: Pairing | None = None
    when: When | None = None
    why: str | None = None
    provenance: Provenance | None = None


@dataclass(frozen=True)
class Surface:
    entries: Mapping[Height, SurfaceRow] = field(default_factory=dict)
    exits: Mapping[Height, SurfaceRow] = field(default_factory=dict)
    pairings: Pairings = field(default_factory=Pairings)
    cells: tuple[CellBinding, ...] = ()
    unlocks: tuple[Unlock, ...] = ()
    require: tuple[str, ...] = ()  # ("entry",) / ("exit",) for join-born stances


@dataclass(frozen=True)
class Bitmap:
    rows: tuple[str, ...]
    y_offset: int = 0

    @property
    def width(self) -> int:
        return max((len(row) for row in self.rows), default=0)

    def row_for_y(self, y: int) -> str | None:
        """The bitmap row at glyph-space y, or None when y is outside the drawing."""
        index = len(self.rows) - 1 - (y - self.y_offset)
        if 0 <= index < len(self.rows):
            return self.rows[index]
        return None


@dataclass(frozen=True)
class Stance:
    name: str
    motion: str
    traits: tuple[str, ...] = ()
    bitmap: Bitmap = field(default_factory=lambda: Bitmap(()))
    bitmaps: Mapping[str, Bitmap] = field(default_factory=dict)
    surface: Surface = field(default_factory=Surface)


@dataclass(frozen=True)
class PolicyRecord:
    """One rider (refuse, prefer, extend, contract, or resolve), in the record shape of design section 3.3. `id` lets a resolve's `against:` name the record. `against`, `pick`, and `migrated` are used only by resolve records (design section 5.8)."""

    kind: str
    when: When = field(default_factory=When)
    id: str | None = None
    stance: str | None = None
    entry: Height | None = None
    exit: Height | None = None
    cell: Mapping[str, str] | None = None  # cell-grain prefer target
    over: Mapping[str, str] | None = None
    mode: str | None = None  # prefer: "yields-to-joins" (default) | "absolute"
    by: int | None = None
    ok: tuple[int, int] | None = None
    bind: str | None = None
    trim: int | None = None
    split: tuple[int, int] | None = None
    against: tuple[str, str | None] | None = None  # (rune, record id) the resolve arbitrates against
    pick: Mapping[str, str] | None = (
        None  # the winning cell pattern (or {stance: ...}) at the conflicted window
    )
    migrated: str | None = None
    why: str | None = None
    provenance: Provenance | None = None


@dataclass(frozen=True)
class Policy:
    order: tuple[str, ...] = ()
    refuse: tuple[PolicyRecord, ...] = ()
    prefer: tuple[PolicyRecord, ...] = ()
    extend: tuple[PolicyRecord, ...] = ()
    contract: tuple[PolicyRecord, ...] = ()
    resolve: tuple[PolicyRecord, ...] = ()
    groups: Mapping[str, frozenset[str]] = field(default_factory=dict)  # membership resolved by spec_load


@dataclass(frozen=True)
class Rune:
    name: str
    codepoint: int | None = None
    sequence: tuple[str, ...] | None = None  # ligature runes declare this instead of a codepoint
    ductus: Mapping[str, str] = field(default_factory=dict)  # motion name -> hand-drawing prose
    notes: str | None = None
    mono: Bitmap | None = None
    stances: Mapping[str, Stance] = field(default_factory=dict)
    policy: Policy = field(default_factory=Policy)

    @property
    def default_stance(self) -> str:
        if self.policy.order:
            return self.policy.order[0]
        return next(iter(self.stances))


