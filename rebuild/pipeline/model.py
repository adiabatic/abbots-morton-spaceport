@dataclass(frozen=True)
class ResolvedSpec:  # spec_load's output; the input to everything else
    runes: Mapping[str, Rune]  # only the modeled runes
    registry: ScriptRegistry


@dataclass(frozen=True)
class CellPlan:
    """`surface.resolve_cell`'s output: the resolved bindings for one cell. It names a bitmap but holds no ink. `bitmap` is the named sibling the cell is drawn with (None means the stance's base drawing). Anchor x values already include overrides. `safety_checks` lists the (side, height) pairs whose `withdrawal: safe` claim `defects.py` must verify. `convention_exempt` names the sides ("entry", "exit") whose declared row sets `x_off_convention`, so E-ANCHOR skips those sides only."""

    cell: CellId
    bitmap: str | None = None
    entry_x: int | None = None
    exit_x: int | None = None
    entry_stub: Stub | None = None
    exit_stub: Stub | None = None
    entry_curs_only: tuple[int, int] | None = None  # selectable: false anchor kept for GPOS parity
    exit_ink_y: int | None = None
    convention_exempt: tuple[str, ...] = ()
    safety_checks: tuple[tuple[str, Height], ...] = ()
    unlock: Unlock | None = None  # set when the cell exists only via this unlock row

    @property
    def needs_safety_check(self) -> bool:
        return bool(self.safety_checks)


@dataclass(frozen=True)
class GlyphRecord:
    """`geometry.realize`'s output: one compiled glyph. Anchors are (x, y) in glyph-space pixels. `name` is the compiled glyph name. `run_m1` names each settled cell's glyph with `settle.cell_label` and fails on a label over `geometry.MAX_GLYPH_NAME_BYTES`. When no name is passed, `realize` uses `geometry.display_name`, which cuts a long name and appends a hash."""

    name: str
    bitmap: tuple[str, ...]
    y_offset: int = 0
    entry: tuple[int, int] | None = None
    exit: tuple[int, int] | None = None
    entry_curs_only: tuple[int, int] | None = None
    advance_width: int | None = None
    exit_ink_y: int | None = None
    convention_exempt: tuple[str, ...] = ()  # sides exempt from E-ANCHOR ("entry"/"exit")
    safety_checks: tuple[tuple[str, Height], ...] = ()
    provenance: str = ""


Adjustment = (
    tuple[Literal["locked"], None, None]
    | tuple[Literal["ext", "con", "trim"], str, int]
    | tuple[Literal["bind"], str, str]
)


def parse_adjustment(token: str) -> Adjustment:
    """Split an adjustments token into (operation, side, argument): ("locked", None, None), ("ext", "en", 1), ("bind", "ex", "pulled-back-stubless"). The return is a union discriminated on the operation, so a caller that rules out "locked" gets a non-optional side."""
    if token == "locked":
        return ("locked", None, None)
    side, _, rest = token.partition("-")
    if side not in ("en", "ex") or not rest:
        raise ValueError(f"unrecognized adjustments token: {token!r}")
    op, _, argument = rest.partition("-")
    if op in ("ext", "con", "trim"):
        return (op, side, int(argument))
    if op == "bind":
        return ("bind", side, argument)
    raise ValueError(f"unrecognized adjustments token: {token!r}")


def feature_config_token(features: Collection[str]) -> str:
    enabled = sorted(features)
    return "+".join(enabled) if enabled else "default"


def relevant_marker_features(rune: Rune) -> tuple[str, ...]:
    """Returns the stylistic sets named by this rune's unlock rows, which are the sets it has marker twins for. A policy record gated on a feature reads the neighbor's marker instead, so it adds nothing here."""
    features: set[str] = set()
    for stance in rune.stances.values():
        for unlock in stance.surface.unlocks:
            features.add(unlock.feature)
    return tuple(sorted(features))


def marker_glyph_name(rune_name: str, active: Collection[str]) -> str:
    """Returns the marker-twin name for a rune under the active relevant features, or the bare name when none are active. Several sets are joined in sorted order: ss02+ss03 gives qsTea.ss02_ss03."""
    enabled = sorted(active)
    if not enabled:
        return rune_name
    return f"{rune_name}.{'_'.join(enabled)}"


def locked_glyph_name(raw_name: str) -> str:
    """Returns the name of the ZWNJ chokepoint twin of a raw input glyph (a bare rune or a marker twin)."""
    return f"{raw_name}.noentry"


def raw_rename_map(spec: ResolvedSpec | None, features: frozenset[str]) -> dict[str, str]:
    """Returns the marker fold for a configuration, the renaming of raw labels to marker twins: each rune whose unlock rows name an active set maps to its marker twin, and its chokepoint twin maps to the marker's chokepoint twin. The marker lookups rename every occurrence of such a rune before settlement runs, so settlement never sees its bare label. Returns an empty map when `spec` is None."""
    renames: dict[str, str] = {}
    if spec is None:
        return renames
    for rune_name, rune in spec.runes.items():
        relevant = frozenset(relevant_marker_features(rune)) & features
        if not relevant:
            continue
        marker = marker_glyph_name(rune_name, relevant)
        renames[rune_name] = marker
        renames[locked_glyph_name(rune_name)] = locked_glyph_name(marker)
    return renames


def isolated_overlay_active(spec: ResolvedSpec, features: Collection[str]) -> bool:
    """Returns whether any active feature is registered with `overlay: isolated` (ss10). Under such a feature the emitted font replaces every letter's cmap glyph with its anchor-free `.ss10` twin before formation, so no ligature forms, nothing settles, and every seam is a break. Such a configuration has no settlement table, and consumers use the isolated stream instead (`settle.isolated_overlay_settled`)."""
    return any(
        spec.registry.features.get(feature) is not None
        and spec.registry.features[feature].overlay == "isolated"
        for feature in features
    )


SS10_TWIN_SUFFIX = ".ss10"


def ss10_twin_name(raw_name: str) -> str:
    """Returns the name of the ss10 twin of a letter's raw cmap glyph. The twin is drawn like the bare glyph but has no cursive anchors and no cmap entry, and no formation, marker, chokepoint, or settlement lookup takes it as input. Substituting it before formation therefore keeps the letter out of every join: no ligature forms, nothing settles, and each letter stays its own cluster."""
    return f"{raw_name}{SS10_TWIN_SUFFIX}"
